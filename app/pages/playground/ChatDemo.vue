// Demo controls
const addStreamingMessage = () => {
  isLoading.value = true;

  setTimeout(() => {
    const streamingMessage: Message = {
      id: `streaming-${Date.now()}`,
      role: "assistant",
      content:
        "This is a simulated streaming response that demonstrates how the typing indicator works and how messages appear in real-time.",
      timestamp: new Date(),
      isStreaming: true,
    };

    messages.value.push(streamingMessage);
    isLoading.value = false;
