<script setup lang="ts">
import { ChatContainer } from "~/components/Chat";
import type { Message, Thread, FileAttachment } from "~/components/Chat/types";

// Demo state
const messages = ref<Message[]>([]);

const isLoading = ref(false);
const currentThread = ref<Thread>({
  id: "demo-thread",
  title: "Nuxt 3 Data Fetching",
  createdAt: new Date(Date.now() - 6 * 60 * 1000),
  updatedAt: new Date(),
  messages: [],
});

// Event handlers
const handleMessageSubmit = async (
  content: string,
  attachments?: FileAttachment[]
) => {
  // Add user message
  const userMessage: Message = {
    id: `user-${Date.now()}`,
    role: "user",
    content,
    timestamp: new Date(),
    attachments,
  };
  messages.value.push(userMessage);

  // Simulate AI response
  isLoading.value = true;

  setTimeout(() => {
    const aiMessage: Message = {
      id: `ai-${Date.now()}`,
      role: "assistant",
      content: `Thanks for your question: "${content}"\n\nThis is a demo response. In a real implementation, this would be generated by your AI model based on your knowledge base and context.`,
      timestamp: new Date(),
      metadata: {
        model: "demo-model",
        tokenUsage: {
          prompt: content.length,
          completion: 150,
          total: content.length + 150,
        },
      },
    };

    messages.value.push(aiMessage);
    isLoading.value = false;
  }, 2000);
};

